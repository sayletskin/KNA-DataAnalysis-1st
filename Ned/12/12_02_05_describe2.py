# 설비 센서 데이터의 "한 열(1 column)"을 묘사

import pandas as pd
import os

path = os.path.join("data", "12_metro_compressor.csv")

df = pd.read_csv(path, encoding="utf-8")
df.info()

# 오일온도만 .describe()으로 꺼내 통계보기
print(df["오일온도"].describe())
# count    199.000000
# mean      63.181910
# std        6.249822
# min       50.100000
# 25%       58.100000
# 50%       62.900000
# 75%       68.100000
# max       75.000000
# Name: 오일온도, dtype: float64

# 1 평균·min·max·중앙값을 문장에 정확히 넣었는가
# 이 값은 보통 OO 정도이고, 가장 낮을 때 OO, 높을 때 OO 형식 -> 문장을 주석으로 만들어주세요
# 평균 63.181910, 최소값 50.100000, 최대값 75.000000, 표준편차 6.249822 

# 2 표준편차를 보고 안정성을 판단했는가
# 표준편차로 안정적인지 들쭉날쭉한지 판단 (AI에게 판단을 시켜보셔도 좋겠어요)
# 변동계수(CV) ≈ 6.25 / 63.18 × 100 = 약 9.9%
# 일반적으로 CV가 10% 안팎이면 변동성이 낮은 편으로 볼 수 있습니다.
# 결론
# 오일온도 데이터의 표준편차 6.25는 평균 63.18에 비해 약 9.9% 수준이므로, 
# 변동성이 비교적 낮고 안정적인 편이라고 판단할 수 있습니다.

# 3 숫자를 그냥 옮기지 않고 의미로 풀어 썼는가
# 숫자만 옮기지 말고 의미로 풀어 쓰기 (참고사항)
# 변동계수가 10% 안팎이므로 변동성이 비교적 낮고 안정적인 
# 오일온도는 평균 63.18℃에서 작동되고 있습니다.

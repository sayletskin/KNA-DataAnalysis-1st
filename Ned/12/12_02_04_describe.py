# 평균/분위수/최대를 읽어 이상 신호 있는 열 찾기
#
# - df.describe() 결과를 가로질러 읽으며 이상치(Outlier) 신호를 탐지합니다.
# - ★ 이상 탐지 핵심 노하우: 75% 분위수 지점과 max(최댓값) 수치의 거리를 비교합니다!
#   * 75% 지점 수치와 max 수치가 가깝다 -> 값이 고르게 분포한 정상 상태
#   * 75% 지점 수치와 max 수치의 간격이 지나치게 멀다 -> 상위 극단치가 존재하는 이상 과열 신호! (추가 조사 필요)
# -----------------------------------------------------------------------------

import pandas as pd
import os

path_compressor = os.path.join("data", "12_metro_compressor.csv")

# 12_metro_compressor.csv
# 온도·진동에 이상값 존재
df_compressor = pd.read_csv(path_compressor, encoding="utf-8")
# print(df_compressor.shape) # (200, 7)
# print(df_compressor.head(3))
# print(df_compressor.tail(3))
df_compressor.info() # print내장o

# STEP1 : describe 후75%와 max 차이큰 열 찾기
print(df_compressor.describe()) # print내장x 
#              압축압력        배출압력        저장압력        오일온도  모터전류
# count  200.000000  200.000000  200.000000  199.000000  200.000000
# mean     9.172200   -0.016950    9.171400   63.181910    2.060850
# std      0.583699    0.047173    0.582497    6.249822    2.196505
# min      8.130000   -0.030000    8.130000   50.100000    0.030000
# 25%      8.700000   -0.020000    8.697500   58.100000    0.040000
# 50%      9.175000   -0.020000    9.175000   62.900000    0.040000
# 75%      9.665000   -0.020000    9.655000   68.100000    3.812500
# max     10.220000    0.600000   10.220000   75.000000    6.190000

# 1 온도의 평균과 최댓값 차이를 숫자로 적었는가
# 평균 75 대 max 75.0 — 차이를 기록
print(round(75.000000 - 63.181910, 6)) # 11.81809

# 2 75%와 max 차이가 큰 열을 두 개 이상 찾았는가
# 온도와 진동— max가 멀리 튄 열 찾기
# "CSV에서 직접 해당 row를 찾아서 주석으로 붙여주세요!"
print(df_compressor[df_compressor["오일온도"] == 75])
# 109  2020-03-03 12:36:57  10.19 -0.02  10.18  75.0  3.79   가동
# 162  2020-03-05 08:35:57  10.18 -0.02  10.18  75.0  3.75   가동

# 3 모터전류처럼 고른 열과 비교해 차이를 설명
# 모터전류는 75%와 max가 가까움— 온도와의 차이 설명
print(round(75.000000 - 68.100000, 6)) # 6.9 , 오일온도
print(round(6.190000 - 3.812500, 6)) # 2.3775 , 모터전류
# 오일온도 75%와 max의 차이는 6.9
# 하위 구간에서의 차이보다 큰 간격이 생겼기 때문에
# 상위 극단치가 생겨 위험하다고 판단됨
# 모터전류 75%와 max의 차이는 2.3775
# 하위 구간에서의 차이와 간격이 작기 때문에
# 상위 극단치의 가능성이 낮다고 판단됨

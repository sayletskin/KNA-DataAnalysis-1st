# 실습 3. 키워드 인자로 함수 호출하기
# 1) 매개변수 두개를 가진 함수를 정의
def report(name, temp):
    print(f"{name} {temp}도")

# 2) 호출할 때 매개변수 이름을 지정해 값을 전달
report(name = "모터", temp = 78) # 모터 78도
# 3) 키워드로 전달하면 순서를 바꿔도 같은 결과인지 확인
report(temp = 78, name = "모터") # 모터 78도
# 4) 위치 인자와 키워드 인자 섞을 때 위치가 먼저인지 확인
report("모터", temp = 78) # 모터 78도